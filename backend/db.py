"""Postgres：用户、模拟账户、持仓、委托、资产快照、自选。

- 连接串用环境变量 DATABASE_URL；本机不设就连 postgresql://localhost/stock_kline（brew 装的 Postgres）。
- 部署到 Vercel 时用 Neon 的 pooled 连接串（带 -pooler 的那个），serverless 每次请求开连接也扛得住。
- 表结构第一次连库时自动建（create ... if not exists），多个实例同时启动用 advisory lock 排队。
"""
from __future__ import annotations

import os
import threading
from contextlib import contextmanager
from datetime import datetime, timezone
from typing import Iterator

import psycopg
from psycopg.rows import dict_row

DATABASE_URL = os.environ.get("DATABASE_URL", "postgresql://localhost/stock_kline")

SCHEMA = """
create table if not exists users (
    id bigint generated by default as identity primary key,
    username text not null,
    password_hash text not null,          -- scrypt$盐$哈希
    created_at text not null
);
-- 用户名不区分大小写唯一
create unique index if not exists ux_users_username on users (lower(username));
create table if not exists accounts (
    user_id bigint primary key references users(id) on delete cascade,
    cash double precision not null,
    initial_cash double precision not null,
    created_at text not null
);
create table if not exists positions (
    user_id bigint not null references users(id) on delete cascade,
    symbol text not null,
    qty bigint not null,
    avg_cost double precision not null,
    primary key (user_id, symbol)
);
create table if not exists orders (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id) on delete cascade,
    symbol text not null,
    side text not null,            -- buy / sell
    type text not null,            -- market / limit
    qty bigint not null,
    limit_price double precision,
    status text not null,          -- pending / filled / cancelled / rejected
    fill_price double precision,
    reason text,
    created_at text not null,
    filled_at text
);
create index if not exists ix_orders_user on orders(user_id, status);
create table if not exists equity_snapshots (
    user_id bigint not null references users(id) on delete cascade,
    ts bigint not null,            -- 记录时间（UTC 秒）
    et_day text not null,          -- 美东日期，算「今日盈亏」用
    equity double precision not null,
    cash double precision not null,
    market_value double precision not null,
    primary key (user_id, ts)
);
create table if not exists login_fails (
    username text not null,        -- 小写
    ts bigint not null
);
create index if not exists ix_login_fails on login_fails(username, ts);
create table if not exists watchlists (
    user_id bigint primary key references users(id) on delete cascade,
    items jsonb not null,          -- [{symbol, name}]
    updated_at text not null
);
"""

_ready = False
_ready_lock = threading.Lock()


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _connect() -> psycopg.Connection:
    # prepare_threshold=None：Neon 的连接池（PgBouncer）下不用服务端预编译语句
    return psycopg.connect(DATABASE_URL, row_factory=dict_row, prepare_threshold=None)


def init() -> None:
    """建表（幂等）。每个进程第一次连库时跑一次。"""
    global _ready
    with _ready_lock:
        if _ready:
            return
        with _connect() as c:
            c.execute("select pg_advisory_xact_lock(424242)")
            c.execute(SCHEMA)
        _ready = True


@contextmanager
def conn() -> Iterator[psycopg.Connection]:
    """每次请求开一个连接、一个事务：正常结束自动提交，抛异常自动回滚。"""
    init()
    with _connect() as c:
        yield c


def lock_user(c: psycopg.Connection, uid: int) -> None:
    """同一个用户的下单 / 撮合 / 撤单排队执行，锁到这个事务结束。多实例部署时也有效。"""
    c.execute("select pg_advisory_xact_lock(1, %s)", (uid,))


if __name__ == "__main__":
    init()
    print("表结构已就绪：", DATABASE_URL.split("@")[-1])
